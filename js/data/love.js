function detectLoveTopic(text) {
  const t = text.toLowerCase();

  if (/(отверг|отказал|отказала|сказала.*нет|сказал.*нет|не взаимн|не любит меня)/.test(t)) {
    return "rejection";
  }
  if (/(не могу.*(думать|забыть)|зацикл|постоянно.*думаю|не выходит.*головы)/.test(t)) {
    return "obsessive";
  }
  if (/(сильн.*люб|очень.*влюб|не могу.*без|жить не могу)/.test(t)) {
    return "strongLove";
  }
  if (/(жду.*ответ|надеюсь|может.*скажет|ждёт|надежда)/.test(t)) {
    return "hope";
  }
  if (/(ревную|ревность|обидно.*(друг|подруг)|общается.*друг)/.test(t)) {
    return "jealousy";
  }
  if (/(не могу.*совладать|не справляюсь|не знаю.*делать|тяжело.*справиться)/.test(t)) {
    return "selfControl";
  }
  if (/(не могу.*сказать|боюсь.*признаться|тайно.*люб|никому.*не говорю)/.test(t)) {
    return "secret";
  }
  if (/(я.*не достоин|я.*недостоин|почему я|я.*плохой|я.*никому.*не нужен)/.test(t)) {
    return "selfWorth";
  }

  return null;
}

function formatLoveSupport(topic) {
  const data = LOVE_SUPPORT[topic];
  if (!data) return null;

  let out = `${data.title}\n\n`;

  if (data.phrases) {
    out += pick(data.phrases) + "\n\n";
  }

  if (data.steps) {
    out += "🛠 Что можно сделать:\n\n";
    data.steps.forEach(s => out += `${s}\n`);
    out += "\n";
  }

  if (data.techniques) {
    out += "🧘 Техники:\n\n";
    data.techniques.forEach(t => out += `• ${t}\n`);
    out += "\n";
  }

  if (data.warning) {
    out += `\n${data.warning}`;
  }

  return out.trim();
}