// Плоский список всех вопросов (для случайного выбора)
const ALL_QUESTIONS = Object.values(QUESTIONS).flat();

// Получить случайный вопрос, который ещё не задавали
function getRandomQuestion(usedQuestions = []) {
  const available = ALL_QUESTIONS.filter(q => !usedQuestions.includes(q));
  if (available.length === 0) return null;
  return available[Math.floor(Math.random() * available.length)];
}