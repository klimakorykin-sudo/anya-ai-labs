  handle(text) {
    const t = text.toLowerCase();

    if (/(болит|больно|боль|болеет|ломит|щиплет|колет|жжёт|жет|режет|тянет|чешется|зудит)/.test(t)
        || /(эрекц|поллюц|менструац|месячн|пмс|овуляц|молочниц|пубертат|созреван|взрослен|прыщ|акне|ломка голос|скачок роста|волос.*тел|запах.*пот|перепад.*настроени)/.test(t)) {
      for (const [key, pain] of Object.entries(this.pains)) {
        const re = new RegExp("(" + key + ")", "i");
        if (re.test(t)) {
          return { text: this.formatPain(pain) };
        }
      }

      return { text:
        "🫂 Понимаю, что беспокоит.\n\n" +
        "Не могу точно сказать, что это. Вот что делать:\n\n" +
        "1. Скажи родителям — это важно\n" +
        "2. Если боль сильная, не проходит 1–2 часа или есть другие симптомы — обратитесь к врачу\n" +
        "3. Срочно 103: если боль в груди, потеря сознания, сильное кровотечение, затруднённое дыхание\n\n" +
        "📌 Я не врач. Если что-то беспокоит — лучше спросить у родителей или врача. Это не стыдно.\n\n" +
        "Напиши точнее: где именно болит?"
      };
    }

    if (/(система|систему|как устроен|как работает)/.test(t)) {
      for (const [key, sys] of Object.entries(this.systems)) {
        const re = new RegExp(key.split("-")[0], "i");
        if (re.test(t)) {
          return { text: this.formatSystem(sys) };
        }
      }
    }

    if (/(систем.*тела|орган.*систем|какие систем|все систем)/.test(t)) {
      let out = "🫀 СИСТЕМЫ ТЕЛА:\n\n";
      for (const sys of Object.values(this.systems)) {
        out += sys.emoji + " " + sys.name + "\n";
      }
      out += "\nНапиши: «Как устроена сердечно-сосудистая система?»";
      return { text: out };
    }

    if (/(когда.*103|срочно.*врач|красн.*флаг|скорая.*когда|когда.*скорую)/.test(t)) {
      let out = "🚨 СРОЧНО 103 (или 112):\n\n";
      this.redFlags.forEach((f, i) => out += (i + 1) + ". " + f + "\n");
      out += "\n📞 103 — скорая, 112 — единый номер";
      return { text: out };
    }

    return null;
  },

  formatSystem(sys) {
    let out = sys.emoji + " " + sys.name + "\n\n";
    out += "📖 Что это: " + sys.what + "\n\n";
    out += "⚙️ Что делает: " + sys.does + "\n\n";
    out += "🔧 Из чего состоит: " + sys.parts + "\n\n";
    out += "💡 Факт: " + sys.fact;
    return out;
  },

  formatPain(pain) {
    let out = "🫂 Понимаю, " + pain.name + " — это неприятно.\n\n";
    out += "📋 Обычно бывает из-за:\n";
    pain.usual.forEach(u => out += "• " + u + "\n");
    out += "\n🛠 Что сделать сейчас:\n";
    pain.whatToDo.forEach((w, i) => out += (i + 1) + ". " + w + "\n");
    out += "\n⚠️ Обратись к врачу, если:\n";
    pain.doctor.forEach(d => out += "• " + d + "\n");

    if (pain.note) out += "\n💬 " + pain.note;
    out += "\n\n📌 Я не врач. Если что-то беспокоит — скажи родителям и обратитесь к врачу.";
    return out;
  }
