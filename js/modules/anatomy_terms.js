  // ГЛАВНАЯ ФУНКЦИЯ — поиск и объяснение
  // ============================================================
  handle(text) {
    const t = text.toLowerCase();

    // Триггеры: "что такое X", "объясни X", "значение X"
    const isQuestion = /(что такое|объясни|означает|значение|расскажи про|определени)/i.test(t);

    // Ищем термин во всех категориях
    const categories = [
      { name: "anatomy", data: this.anatomy, emoji: "🫀" },
      { name: "biology", data: this.biology, emoji: "🧬" }
    ];

    for (const cat of categories) {
      for (const [term, definition] of Object.entries(cat.data)) {
        // Проверка на точное вхождение термина
        const termRe = new RegExp(`\\b${term}\\b`, "i");
        if (termRe.test(t)) {
          if (isQuestion) {
            return { text: `${cat.emoji} **${term.charAt(0).toUpperCase() + term.slice(1)}**\n\n${definition}` };
          }
        }
      }
    }

    // Если просто написал термин (одно слово) — тоже объясняем
    const trimmed = t.trim();
    if (trimmed.split(/\s+/).length <= 2) {
      for (const cat of categories) {
        if (cat.data[trimmed]) {
          return { text: `${cat.emoji} **${trimmed.charAt(0).toUpperCase() + trimmed.slice(1)}**\n\n${cat.data[trimmed]}` };
        }
      }
    }

    // Список доступных терминов
    if (/(термин|словарь|что знаешь.*анатом|объясни.*орган|анатоми.*термин|биологи.*термин)/.test(t)) {
      return { text:
        "📚 СЛОВАРЬ ТЕРМИНОВ:\n\n" +
        "🫀 Анатомия: аорта, артерия, вена, сердце, нейрон, мозг, лёгкие, желудок, печень, почка, скелет, мышца...\n\n" +
        "🧬 Биология: клетка, ядро, ДНК, РНК, ген, хромосома, митоз, мейоз, эволюция, экосистема...\n\n" +
        "Напиши: «Что такое хромосома?» — объясню!"
      };
    }

    return null;
  }
