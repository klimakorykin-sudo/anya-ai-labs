// ============================================================
// DISCRETE.JS — Дискретная математика
// ============================================================

const DiscreteModule = {

  handle(text) {
    const t = text.toLowerCase();

    // === МНОЖЕСТВА ===
    if (/(множеств|объединени|пересечени|подмножеств|set theory)/.test(t)) {
      return { text:
        "📐 МНОЖЕСТВА:\n\n" +
        "**Множество** — совокупность объектов.\n" +
        "Пример: A = {1, 2, 3}\n\n" +
        "**Обозначения**:\n" +
        "• a ∈ A — «a принадлежит A»\n" +
        "• a ∉ A — «a не принадлежит A»\n" +
        "• ∅ — пустое множество\n\n" +
        "**Операции**:\n" +
        "• **Объединение** A ∪ B — все элементы обоих\n" +
        "• **Пересечение** A ∩ B — только общие\n" +
        "• **Разность** A \\ B — элементы A без B\n" +
        "• **Симметричная разность** A △ B — все, кроме общих\n" +
        "• **Дополнение** ¬A — всё, кроме A\n\n" +
        "**Пример**:\n" +
        "A = {1, 2, 3}, B = {3, 4, 5}\n" +
        "A ∪ B = {1, 2, 3, 4, 5}\n" +
        "A ∩ B = {3}\n" +
        "A \\ B = {1, 2}\n\n" +
        "**Мощность** |A| — количество элементов."
      };
    }

    // === КОМБИНАТОРИКА ===
    if (/(комбинатор|перестановк|сочетани|размещени|факториал)/.test(t)) {
      return { text:
        "📐 КОМБИНАТОРИКА:\n\n" +
        "**Факториал**: n! = 1·2·3·...·n\n" +
        "• 3! = 6\n" +
        "• 5! = 120\n" +
        "• 0! = 1\n\n" +
        "**Перестановки** P(n) = n!\n" +
        "Сколькими способами расставить n объектов.\n" +
        "Пример: 3 книги → 3! = 6 способов\n\n" +
        "**Размещения** A(n,k) = n! / (n-k)!\n" +
        "Выбрать k из n и упорядочить.\n" +
        "Пример: A(5,2) = 20\n\n" +
        "**Сочетания** C(n,k) = n! / (k!·(n-k)!)\n" +
        "Выбрать k из n без порядка.\n" +
        "Пример: C(5,2) = 10\n\n" +
        "**Примеры**:\n" +
        "• Сколько способов выбрать 2 из 5 друзей? → C(5,2)=10\n" +
        "• Сколько паролей из 4 цифр? → 10⁴=10 000"
      };
    }

    // === ГРАФЫ ===
    if (/(граф|вершин|рёбер|ребер|дерев.*граф|bfs|dfs)/.test(t)) {
      return { text:
        "📐 ГРАФЫ:\n\n" +
        "**Граф** — множество вершин и рёбер между ними.\n" +
        "Обозначение: G = (V, E)\n\n" +
        "**Виды**:\n" +
        "• **Неориентированный** — рёбра без направления\n" +
        "• **Ориентированный (орграф)** — со стрелками\n" +
        "• **Взвешенный** — с числами на рёбрах\n" +
        "• **Дерево** — без циклов, связный\n" +
        "• **Полный** — все вершины связаны\n\n" +
        "**Примеры**:\n" +
        "• Карта дорог\n" +
        "• Соцсеть (друзья)\n" +
        "• Интернет\n\n" +
        "**Обходы**:\n" +
        "• **BFS** (в ширину) — по уровням\n" +
        "• **DFS** (в глубину) — вглубь\n\n" +
        "**Задачи**:\n" +
        "• Кратчайший путь (Дейкстра)\n" +
        "• Минимальное остовное дерево"
      };
    }

    // === ЛОГИКА (дискретная) ===
    if (/(дискретн.*логик|булев.*алгебр|импликац|эквиваленц|де морган)/.test(t)) {
      return { text:
        "📐 ЛОГИКА (дискретная):\n\n" +
        "**Операции**:\n" +
        "• ¬A — отрицание\n" +
        "• A ∧ B — конъюнкция (И)\n" +
        "• A ∨ B — дизъюнкция (ИЛИ)\n" +
        "• A → B — импликация (если A, то B)\n" +
        "• A ↔ B — эквивалентность (A = B)\n\n" +
        "**Импликация** A → B:\n" +
        "Ложна только если A истинно, B ложно.\n" +
        "Пример: «Если дождь → я беру зонт»\n" +
        "• Дождь + зонт = правда\n" +
        "• Дождь без зонта = ложь\n" +
        "• Без дождя = правда (не важно, взял зонт или нет)\n\n" +
        "**Законы**:\n" +
        "• Де Моргана: ¬(A ∧ B) = ¬A ∨ ¬B\n" +
        "• Де Моргана: ¬(A ∨ B) = ¬A ∧ ¬B\n" +
        "• Дистрибутивности: A ∧ (B ∨ C) = (A ∧ B) ∨ (A ∧ C)"
      };
    }

    // === ОТНОШЕНИЯ ===
    if (/(отношени|рефлексивн|симметричн|транзитивн|антисимметр)/.test(t)) {
      return { text:
        "📐 ОТНОШЕНИЯ:\n\n" +
        "**Бинарное отношение** — связь между элементами.\n" +
        "Пример: «<» на числах, «=», «друг».\n\n" +
        "**Свойства**:\n" +
        "• **Рефлексивность**: a ~ a\n" +
        "  Пример: «=» — да, «<» — нет\n" +
        "• **Симметричность**: a ~ b ⇒ b ~ a\n" +
        "  Пример: «друг» — да, «<» — нет\n" +
        "• **Транзитивность**: a ~ b, b ~ c ⇒ a ~ c\n" +
        "  Пример: «<» — да\n" +
        "• **Антисимметричность**: a ~ b, b ~ a ⇒ a = b\n" +
        "  Пример: «≤»\n\n" +
        "**Отношение эквивалентности** — рефлексивно, симметрично, транзитивно.\n" +
        "**Отношение порядка** — рефлексивно, антисимметрично, транзитивно."
      };
    }

    // === МАТЕМАТИЧЕСКАЯ ИНДУКЦИЯ ===
    if (/(индукци|математическ.*индукц)/.test(t)) {
      return { text:
        "📐 МАТЕМАТИЧЕСКАЯ ИНДУКЦИЯ:\n\n" +
        "Метод доказательства утверждений для всех натуральных чисел.\n\n" +
        "**Схема**:\n" +
        "1. **База**: проверить для n = 1 (или n = 0)\n" +
        "2. **Переход**: если верно для n = k, то верно для n = k+1\n" +
        "3. **Вывод**: верно для всех n\n\n" +
        "**Пример**: доказать, что 1 + 2 + ... + n = n(n+1)/2\n" +
        "• База: n=1 → 1 = 1·2/2 = 1 ✓\n" +
        "• Переход: пусть верно для k. Тогда 1+...+k+(k+1) = k(k+1)/2 + (k+1) = (k+1)(k+2)/2 ✓\n" +
        "• Значит, верно для всех n."
      };
    }

    return null;
  }
};
