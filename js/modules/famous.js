  handle(text) {
    const t = text.toLowerCase();

    // Триггеры рассказа про известного человека
    const triggers = /(расскажи.*(про|о)|кто такой|кто такая|что.*(про|о)|информац.*(про|о))/i;

    // Ищем имя в тексте
    for (const [key, person] of Object.entries(this.people)) {
      if (t.includes(key)) {
        // Если есть триггер "расскажи про" — рассказываем
        if (triggers.test(t)) {
          return { text: this.format(person) };
        }
        // Если просто упоминание — тоже рассказываем
        if (t.length < 30) {
          return { text: this.format(person) };
        }
      }
    }

    // Список известных
    if (/(кого.*знаешь|каких.*(писател|учён|учен|людей)|известн.*люд)/.test(t)) {
      return { text:
        "📚 Я знаю много известных людей:\n\n" +
        "✍️ Писатели:\n" +
        "• Пушкин, Чехов, Толстой\n" +
        "• Достоевский, Лермонтов, Гоголь\n" +
        "• Тургенев, Булгаков, Шекспир\n\n" +
        "🔬 Учёные:\n" +
        "• Эйнштейн, Ньютон, Тесла\n" +
        "• Кюри, Менделеев, Ломоносов\n" +
        "• Леонардо да Винчи\n\n" +
        "👑 Исторические:\n" +
        "• Гагарин, Наполеон\n" +
        "• Пётр I, Екатерина II\n\n" +
        "Напиши: «Расскажи про Пушкина»"
      };
    }

    return null;
  },

  format(person) {
    let out = `👤 ${person.name}\n`;
    out += `📅 ${person.years}\n`;
    out += `🎓 ${person.who}\n\n`;
    out += `💡 Интересные факты:\n\n`;
    person.facts.forEach(f => out += `• ${f}\n`);
    return out;
  }
