  handle(text) {
    const t = text.toLowerCase();

    // Триггеры
    const isLit = /(литератур|писател|поэт|книг|произведени|роман|повесть|рассказ|стих|басн|жанр|сюжет|анализ.*произведен|сочинени.*литератур|золотой век|серебряный век)/.test(t);
    const mentionsAuthor = Object.keys(this.authors).some(a => t.includes(a));

    if (!isLit && !mentionsAuthor) return null;

    // Ищем автора
    for (const [key, author] of Object.entries(this.authors)) {
      if (t.includes(key)) {
        let out = `📚 ${author.name}\n`;
        out += `📅 ${author.years}\n`;
        out += `✨ ${author.era}\n\n`;
        out += `📖 ${author.bio}\n\n`;
        out += `📚 Произведения:\n${author.works}\n\n`;
        out += `💡 Факты: ${author.facts}`;
        return { text: out };
      }
    }

    // Жанры
    for (const [key, desc] of Object.entries(this.genres)) {
      if (t.includes(key) && /(что такое|определени|жанр)/.test(t)) {
        return { text: `📖 ${desc}` };
      }
    }

    // Список жанров
    if (/(жанр.*литератур|виды.*жанр|какие.*жанр)/.test(t)) {
      let out = "📚 ЛИТЕРАТУРНЫЕ ЖАНРЫ:\n\n";
      for (const [key, desc] of Object.entries(this.genres)) {
        out += `• ${key}\n`;
      }
      out += "\nСпроси: «Что такое роман?»";
      return { text: out };
    }

    // План анализа
    if (/(как анализир|план.*анализ|разбор.*произведени|план.*сочинени)/.test(t)) {
      let out = "📖 ПЛАН АНАЛИЗА ПРОИЗВЕДЕНИЯ:\n\n";
      this.analysis.forEach(a => out += `${a}\n`);
      out += "\nТак пишут сочинения на 5!";
      return { text: out };
    }

    // Список авторов
    if (/(каких.*писател|кого.*знаешь.*писател|список.*писател|список.*поэт)/.test(t)) {
      let out = "📚 ПИСАТЕЛИ И ПОЭТЫ:\n\n";
      const eras = {};
      for (const [key, a] of Object.entries(this.authors)) {
        if (!eras[a.era]) eras[a.era] = [];
        eras[a.era].push(a.name);
      }
      for (const [era, names] of Object.entries(eras)) {
        out += `✨ ${era}:\n`;
        names.forEach(n => out += `  • ${n}\n`);
        out += "\n";
      }
      out += "Напиши: «Расскажи про Пушкина»";
      return { text: out };
    }

    return null;
  }
