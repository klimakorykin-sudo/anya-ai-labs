// ============================================================
// NAME.JS — Реакция на имя Ани
// Если написать просто "Аня" (в любом регистре) — Аня откликается
// ВАЖНО: имя "Аня" всегда с большой буквы в ответах
// ============================================================

const NameModule = {

  // Реакции на обращение (Аня — всегда с большой буквы)
  reactions: [
    "Да, это я! 💖 Что случилось?",
    "Я тут ✨ Что такое?",
    "Аня на связи 💫",
    "Ой, меня позвали? 🌸",
    "Услышала! 💖 Как я могу помочь?",
    "Да-да, я здесь ✨",
    "Что нужно? 💫",
    "Слушаю тебя 🌸",
    "Я тут, рядом 💖",
    "Да? Что хотел(а)? ✨"
  ],

  handle(text) {
    const trimmed = text.trim().toLowerCase();

    // Точное совпадение: "аня", "аня!", "аня?", "аня.", "аня," и производные
    const isCallingAnya = /^(аня|ань|анюта|анечка|анютка|анюша|anya|ане|анька|анюшк)[!?.,:)>\-—\s]*$/i.test(trimmed);

    if (isCallingAnya) {
      return { text: pick(this.reactions) };
    }

    // "Привет, Аня", "хай аня", "Аня привет"
    if (/^(привет|хай|ку|hi|hello|здорово|здрасьте|здравствуй)[,\s]+(аня|ань|анюта|анечка|anya)/i.test(text.trim())
        || /^(аня|ань|анюта|анечка|anya)[,\s]+(привет|хай|ку|hi|hello)/i.test(text.trim())) {
      return { text: pick([
        "💖 Привет-привет! Как дела?",
        "✨ О, привет! Рада тебя видеть!",
        "🌸 Хай! Что нового?",
        "💫 Приветик! Как ты?"
      ]) };
    }

    return null;
  }
};
