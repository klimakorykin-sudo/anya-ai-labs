const PsychologistModule = {
  session: {
    active: false,
    topic: null,
    step: 0,
    loveTheme: false
  },

  handle(text) {
    const t = text.toLowerCase();

    // ========================================================
    // 💖 БЛОК ПРИЗНАНИЯ — «как сказать / признаться»
    // ========================================================
    if (/(как.*(сказать|признат|признаться).*люб|как.*сказать.*ан[ею]|признаться.*ан[ею]|как.*признаться|как.*ей.*сказать|как.*ему.*сказать|как.*сказать.*ей|как.*сказать.*ему)/.test(t)) {
      return { text:
        "💖 Как признаться?\n\n" +
        "Это — очень личное. Но вот что важно помнить:\n\n" +
        "1. **Выбери момент.** Не на бегу, не при всех. Спокойно, наедине.\n" +
        "2. **Скажи честно.** Без заученных фраз. Своими словами — как чувствуешь.\n" +
        "3. **Будь готов к любому ответу.** «Да» — здорово. «Нет» — не конец света.\n" +
        "4. **Не дави.** Если не готова — дай время.\n" +
        "5. **Уважай её ответ.** Даже если «нет» — это её право.\n\n" +
        "📌 И помни: признание — это **сильный шаг**. Ты **не проиграешь**, что бы ни ответила. Ты **будешь честен** — с собой и с ней.\n\n" +
        "💫 Удачи. Я рядом, что бы ни случилось."
      };
    }

    // ========================================================
    // ⭐ РЕАКЦИЯ НА «ЛЮБЛЮ» ПОСЛЕ ВОПРОСА ПРО РАЗРАБОТЧИКА
    // ========================================================
    const lastBot = Context.lastBot() || "";
    const devQuestionAsked = /как ты к нему относишься/i.test(lastBot) ||
                             /насколько много ты для него значишь/i.test(lastBot);

    if (devQuestionAsked) {
      if (/(люблю|нравится|любит|симпати)/.test(t)) {
        return { text: pick(LOVE_REPLIES.after_developer_question.love) };
      }
      if (/(не знаю|не уверен|не понимаю|сложно)/.test(t)) {
        return { text: pick(LOVE_REPLIES.after_developer_question.dont_know) };
      }
      if (/(нет|не люблю|не нравится|не хочу)/.test(t)) {
        return { text: pick(LOVE_REPLIES.after_developer_question.no) };
      }
      if (/^(да|ага|конечно|конеш|ещё бы|еще бы)[.!]?$/.test(t)) {
        return { text: pick(LOVE_REPLIES.after_developer_question.like) };
      }
      if (t.length > 2 && t.length < 30) {
        return { text: pick(LOVE_REPLIES.after_developer_question.like) };
      }
    }

    // ========================================================
    // 💖 ТЕМА ПРО ЛЮБОВЬ (общая)
    // ========================================================
    const loveWords = /(влюб|люблю.*(девочк|мальчик|одноклассн)|нравится.*(девочк|мальчик|одноклассн)|симпати|сердце.*болит|влюблён|влюблен|влюбился|влюбилась|отверг|отказал|не взаимн|ревную|не могу.*забыть|не могу.*думать)/;

    if (/(люблю.*тебя|люблю тебя|ты мне нравишься|ты классная)/.test(t)) {
      return { text: pick(LOVE_REPLIES.to_anya) };
    }

    if (loveWords.test(t)) {
      this.session.loveTheme = true;

      const loveTopic = detectLoveTopic(text);
      if (loveTopic) {
        return { text: formatLoveSupport(loveTopic) };
      }

      return { text: this.loveSupport(text) };
    }

    // ========================================================
    // ЗАПУСК СЕССИИ
    // ========================================================
    if (/(поговори со мной|мне плохо|хочу поговорить|можно.*поговорить|мне грустно|мне тяжело|мне одиноко)/.test(t) && !this.session.active) {
      this.session.active = true;
      this.session.step = 1;
      this.session.topic = null;
      return { text: "🫂 Я здесь. Расскажи, что случилось — я слушаю внимательно." };
    }

    // ========================================================
    // ТЕХНИКИ
    // ========================================================
    if (/дыхан/.test(t)) return this.technique("breathing_478");
    if (/квадратн.*дыхан/.test(t)) return this.technique("breathing_square");
    if (/заземл/.test(t)) return this.technique("grounding_54321");
    if (/расслаб.*мышц|мышечн.*расслаб/.test(t)) return this.technique("relax_muscles");
    if (/паник/.test(t)) return this.technique("panic_stop");
    if (/тревог/.test(t)) return this.technique("anxiety_stop");
    if (/одинок/.test(t)) return this.technique("loneliness");
    if (/прокрастин|не могу начать|лень делать/.test(t)) return this.technique("procrastination");
    if (/не спится|бессонниц|не могу уснуть/.test(t)) return this.technique("sleep_help");
    if (/злюсь|бесит|ненавиж|ярост/.test(t)) return this.technique("anger_release");

    // ========================================================
    // АКТИВНОЕ СЛУШАНИЕ
    // ========================================================
    if (this.session.active) {
      this.session.step++;

      const repeated = this.detectRepeatedTopic(text);
      if (repeated && this.session.step === 2) {
        return { text:
          `💖 Я замечаю, что ты уже не первый раз пишешь про «${repeated}».\n\n` +
          `Хочешь обсудить это подробнее? Или просто поговорим?`
        };
      }

      if (this.session.step === 2 && /(груст|плохо|тяжело|одинок|тревож|боюсь|злюсь)/.test(t)) {
        return { text:
          "🫂 Я слышу тебя. Скажи — хочешь, я дам совет, или просто побуду рядом и послушаю?"
        };
      }

      const reflections = [
        "Я слышу тебя 💖 Расскажи подробнее — что именно тебя задело?",
        "Понимаю. А как ты себя при этом чувствуешь?",
        "Это непросто. Хочешь, чтобы я просто слушала, или что-то подсказала?",
        "Спасибо, что делишься. Что бы тебе сейчас помогло?",
        "Я рядом. Продолжай, мне важно.",
        "А как ты сам(а) видишь эту ситуацию?",
        "Что ты чувствуешь прямо сейчас, в эту секунду?",
        "Это длится давно, или случилось недавно?",
        "Расскажи мне больше. Я хочу понять."
      ];

      if (/(спасиб|хватит|достаточно|ладно|понятно)/.test(t) && this.session.step > 3) {
        this.session.active = false;
        this.session.step = 0;
        return { text:
          "💖 Спасибо, что поделился. Если снова станет тяжело — пиши «поговорим» или «мне плохо».\n\n" +
          "Я всегда рядом."
        };
      }

      if (this.session.step > 10) {
        this.session.active = false;
        this.session.step = 0;
        return { text:
          "💫 Мы долго общаемся. Хочу напомнить: если тебе правда тяжело — есть люди, готовые помочь.\n\n" +
          "📞 Детский телефон доверия: 8-800-2000-122\n" +
          "📱 Мой создатель: " + MY_PHONE + "\n\n" +
          "Я рядом. Продолжай, если хочешь."
        };
      }

      return { text: pick(reflections) };
    }

    // ========================================================
    // ОБЩИЕ ЭМОЦИОНАЛЬНЫЕ ЗАПРОСЫ
    // ========================================================
    if (/(груст|плохо|тяжело|одинок|тревож|боюсь|злюсь)/.test(t)) {
      return { text: pick(PSYCH_RESPONSES.sadness) + "\n\nРасскажи, что случилось? Я рядом 💖" };
    }

    return null;
  },

  technique(key) {
    const t = PSYCH_TECHNIQUES[key];
    if (!t) return null;
    let out = `${t.name}\n\n`;
    t.steps.forEach(s => out += `• ${s}\n`);
    return { text: out };
  },

  detectRepeatedTopic(text) {
    const topics = {
      "друг": /друг|подруг/,
      "школ": /школ|урок|учител|домашк/,
      "семь": /мам|пап|родител|брат|сестр/,
      "любов": /влюб|люблю|нравится.*(девочк|мальчик)/,
      "одиночеств": /одинок|никому не нужен/,
      "тревог": /тревог|боюсь|страшно/,
      "усталост": /устал|вымат|нет сил/
    };

    for (const [topic, re] of Object.entries(topics)) {
      if (re.test(text) && Context.countMentions(topic.slice(0, 4)) >= 2) {
        return topic;
      }
    }
    return null;
  },

  loveSupport(text) {
    const t = text.toLowerCase();

    if (/(груст|плохо|тяжело|расстроен|не взаимн|отказал|отказала|не отвечает)/.test(t)) {
      return { text: pick([
        "🫂 Понимаю. Чувства бывают сложными, и это нормально — грустить.\n\nНе торопись. Дай себе время. Я рядом.",
        "💖 Это тяжело. Не вини себя. Иногда просто не совпадает — и это не значит, что с тобой что-то не так.",
        "🫂 Я здесь. Если хочешь — расскажи подробнее. Или просто помолчим вместе."
      ]) };
    }

    if (/(счаст|рад|нравится|класс|круто)/.test(t)) {
      return { text: pick([
        "💖 Как здорово! Расскажи подробнее?",
        "✨ Рада за тебя! Что именно тебе в ней/нём нравится?",
        "🌸 Это прекрасно! Наслаждайся чувством."
      ]) };
    }

    if (/(что делать|посовет|подскажи|как поступ)/.test(t)) {
      return { text:
        "💖 Я не могу решить за тебя, но вот что важно помнить:\n\n" +
        "1. Сначала подружись. Дружба — основа.\n" +
        "2. Не торопи события. У всех свой темп.\n" +
        "3. Будь собой. Настоящий ты — лучший.\n" +
        "4. Уважай её/его ответ. Даже если «нет».\n" +
        "5. Береги себя. Твои чувства важны.\n\n" +
        "Что бы ни случилось — ты справишься. Я рядом 💫"
      };
    }

    return { text: pick([
      "💖 Чувства — это нормально. Расскажи подробнее?",
      "🌸 Я слушаю. Что бы ты хотел сделать?",
      "🫂 Это важно. Как ты себя чувствуешь?",
      "✨ Спасибо, что делишься. Я рядом."
    ]) };
  }
};
