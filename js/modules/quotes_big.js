  handle(text) {
    if (this.allQuotes.length === 0) this.init();

    const t = text.toLowerCase().trim();

    // Триггер: «цитата», «процитируй», «мотивация», «вдохнови», «скажи цитату»
    if (/(цитат|процитируй|мотивируй|мотивац|вдохнови|скажи.*цитат|дай.*цитат|скажи.*мотивац)/.test(t)) {
      // Ищем по теме
      for (const [topic, arr] of Object.entries(this.quotes)) {
        if (t.includes(topic)) {
          return { text: "✨ " + pick(arr) };
        }
      }

      // Если тема не найдена — случайная цитата
      return { text: "✨ " + pick(this.allQuotes) };
    }

    return null;
  }
