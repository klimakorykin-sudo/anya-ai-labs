  async handle(text) {
    const t = text.toLowerCase();

    // Определяем класс пользователя
    let grade = await MemoryDB.get("grade");
    let level = "5-7"; // по умолчанию

    if (grade) {
      const g = parseInt(grade);
      if (g >= 1 && g <= 4) level = "1-4";
      else if (g >= 5 && g <= 7) level = "5-7";
      else if (g >= 8 && g <= 9) level = "8-9";
      else if (g >= 10 && g <= 11) level = "10-11";
      else if (g > 11) level = "student";
    }

    // === Триггеры ===
    const isSexEdQuestion = /(полов|размножен|пубертат|созреван|менструац|эякуляц|поллюц|беременн|сперматозоид|яйцеклетк|зигот|эмбрион|полов.*орган|мальчик.*девочк|различи.*пол|как появляются дети|откуда.*дети|секс|интим|18\+|ЗППП|презерватив|согласи|границ|гигиен.*интим|эрекц|оргазм)/.test(t);

    if (!isSexEdQuestion) return null;

    // === Конкретная тема ===
    for (const [key, topic] of Object.entries(this.topics)) {
      const re = new RegExp(key, "i");
      if (re.test(t)) {
        return { text: `${topic.title}\n\n${topic.text}` };
      }
    }

    // === Общий запрос — по классу ===
    const byGradeData = this.byGrade[level];
    let out = byGradeData.text;
    out += `\n\n(Уровень: ${byGradeData.label}. Скажи «я в X классе» — подберу точнее.)`;
    return { text: out };
  }
